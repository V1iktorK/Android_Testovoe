        public static string[] Map(int level)
        {
            if (level < 1 || level > LEVEL_COUNT)
                throw new System.ArgumentOutOfRangeException("level", "Уровень вне диапазона");
            return Maps[level - 1];
        }

        /// <summary>Сид рандомизации батареек уровня — детерминирован.</summary>
        public static int SeedFor(int level)
        {
            return 104729 * level + 7919;
        }

        /// <summary>Число батареек на уровне (растёт с номером).</summary>
        public static int BatteriesFor(int level)
        {
            return 3 + level / 4;
        }

        /// <summary>Число жизней на уровне.</summary>
        public static int LivesFor(int level)
        {
            return level <= 10 ? 3 : 2;
        }
